'use strict';

// Читаемый адрес в строке браузера.
//
// Ссылки страниц сервер собирает читаемыми сам (ru.crt.web.QueryString.encode: '%'
// шаблона и кириллица остаются как есть), но адрес, по которому посетитель сюда попал,
// читаемым быть не обязан: форма кодирует '%' как %25, ссылку можно набрать руками,
// достать из закладок или получить от старого клиента. Готовый адрес приходит сюда
// атрибутом data-url, и строка браузера переписывается на него.
//
// Здесь нет ни одного правила кодирования: адрес уже посчитан сервером, поэтому правило
// живёт в одном месте и разъехаться ему не с чем.
//
// replaceState, а не assign: страница уже загружена по нужному адресу, перезапрашивать
// её незачем. Запись истории при этом заменяется, поэтому «назад» ведёт туда же, куда
// и раньше, а F5 и копирование из строки браузера дают уже читаемый адрес.
//
// Готовым адресом описан только сам поиск (data-keep перечисляет его параметры), поэтому
// всё остальное — utm-метки, yclid и прочая разметка ссылок — переносится как есть, без
// разбора: адрес должен стать читаемее, а не короче на чей-то счётчик. По той же причине
// скрипт стоит после metrika.js: тот берёт location.href при инициализации, и перепиши
// мы адрес раньше — счётчик увидел бы его уже без меток.
//
// Без JavaScript просто ничего не происходит: адрес остаётся закодированным, все ссылки
// на странице и так читаемы, а поиск работает ровно как работал.

(function () {
  // currentScript пуст у отложенного и переинжектированного скрипта — тогда нам просто
  // нечего читать, и молча ничего не делать здесь правильнее, чем падать в консоль
  const script = document.currentScript;
  if (!script) {
    return;
  }

  const ours = new Set(script.dataset.keep.split(','));
  const foreign = location.search.slice(1).split('&')
    .filter((pair) => pair && !ours.has(pair.split('=')[0]))
    .map((pair) => '&' + pair)
    .join('');

  history.replaceState(null, '', script.dataset.url + foreign);
})();
